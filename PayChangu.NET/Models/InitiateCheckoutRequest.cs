using PayChangu.NET.Json.Converters;
using System;
using System.Text.Json.Serialization;

namespace PayChangu.NET.Models;

/// <summary>
/// Represents a request to initiate a payment using PayChangu Standard Checkout.
/// </summary>
/// <remarks>
/// The request contains the transaction details, customer information,
/// callback and return URLs, checkout customization details, and optional metadata.
/// </remarks>
public sealed class InitiateCheckoutRequest
{
    /// <summary>
    /// Gets or sets the amount to be charged to the customer.
    /// </summary>
    /// <remarks>
    /// The amount must be greater than zero and expressed in the specified currency.
    /// </remarks>
    /// <example>5000</example>
    [JsonPropertyName("amount")]
    [JsonConverter(typeof(PayChanguDecimalJsonConverter))]
    public decimal Amount { get; set; }

    /// <summary>
    /// Gets or sets the currency of the transaction.
    /// </summary>
    /// <remarks>
    /// Defaults to MWK (Malawian Kwacha).
    /// </remarks>
    /// <example>MWK</example>
    [JsonPropertyName("currency")]
    [JsonConverter(typeof(JsonStringEnumConverter))]
    public PayChanguCurrency Currency { get; set; } = PayChanguCurrency.MWK;

    /// <summary>
    /// Gets or sets the customer's email address.
    /// </summary>
    /// <example>customer@example.com</example>
    [JsonPropertyName("email")]
    public string Email { get; set; } = null!;

    /// <summary>
    /// Gets or sets the customer's first name.
    /// </summary>
    [JsonPropertyName("first_name")]
    public string FirstName { get; set; } = null!;

    /// <summary>
    /// Gets or sets the customer's last name.
    /// </summary>
    [JsonPropertyName("last_name")]
    public string LastName { get; set; } = null!;

    /// <summary>
    /// Gets or sets the URL to which PayChangu sends a callback for a
    /// successful transaction.
    /// </summary>
    /// <remarks>
    /// This should point to a publicly accessible page in your application
    /// that handles successful payment callbacks. It is separate from the webhook
    /// endpoint configured in the PayChangu dashboard.
    /// </remarks>
    /// <example>https://example.com/payments/callback</example>
    [JsonPropertyName("callback_url")]
    public string CallbackUrl { get; set; } = null!;

    /// <summary>
    /// Gets or sets the URL to which the customer is redirected when the
    /// checkout process is canceled or fails.
    /// </summary>
    /// <remarks>
    /// Use this URL to return the customer to your application when the checkout
    /// is unsuccessful. Do not rely on the redirect alone to determine the
    /// final status of a transaction.
    /// </remarks>
    /// <example>https://example.com/payment/return</example>
    [JsonPropertyName("return_url")]
    public string ReturnUrl { get; set; } = null!;

    /// <summary>
    /// Gets or sets the unique transaction reference generated by your application.
    /// </summary>
    /// <remarks>
    /// Use this reference to identify and reconcile the transaction
    /// within your application.
    /// </remarks>
    [JsonPropertyName("tx_ref")]
    public string TransactionReference { get; set; } = null!;

    /// <summary>
    /// Gets or sets the checkout customization details displayed to the customer.
    /// </summary>
    [JsonPropertyName("customization")]
    public PaymentCustomization Customization { get; set; } = null!;

    /// <summary>
    /// Gets or sets optional metadata associated with the transaction.
    /// </summary>
    /// <remarks>
    /// Metadata can be used to pass additional application-specific information
    /// with the payment request.
    /// </remarks>
    [JsonPropertyName("meta")]
    public PaymentMeta? Meta { get; set; }
}

/// <summary>
/// Represents the customization details displayed during the checkout process.
/// </summary>
public sealed class PaymentCustomization
{
    /// <summary>
    /// Gets or sets the title displayed during checkout.
    /// </summary>
    [JsonPropertyName("title")]
    public string Title { get; set; } = null!;

    /// <summary>
    /// Gets or sets the description displayed during checkout.
    /// </summary>
    [JsonPropertyName("description")]
    public string Description { get; set; } = null!;
}

/// <summary>
/// Represents optional metadata associated with a payment transaction.
/// </summary>
public sealed class PaymentMeta
{
    /// <summary>
    /// Gets or sets an optional UUID associated with the transaction.
    /// </summary>
    [JsonPropertyName("uuid")]
    [JsonConverter(typeof(PayChanguGuidJsonConverter))]
    public Guid Id { get; set; }

    /// <summary>
    /// Gets or sets an optional response value associated with the transaction.
    /// </summary>
    [JsonPropertyName("response")]
    public string? Response { get; set; }
}